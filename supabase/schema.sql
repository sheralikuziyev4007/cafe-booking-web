-- Coffee&Co database schema for Supabase.
-- Run this file once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Then run supabase/seed.sql to add the starter menu, and create the admin user (see README).

-- ---------------------------------------------------------------------------
-- Helper: is the current user an admin?
-- Admins are accounts whose app_metadata contains {"role": "admin"}.
-- app_metadata cannot be edited by the user, only from the dashboard or with SQL.
-- ---------------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
as $$
  select coalesce((select auth.jwt()) -> 'app_metadata' ->> 'role', '') = 'admin'
$$;

-- ---------------------------------------------------------------------------
-- Menu
-- name / description hold all languages: {"en": "...", "ru": "...", "uz": "..."}
-- ---------------------------------------------------------------------------
create table if not exists public.menu_items (
  id           uuid primary key default gen_random_uuid(),
  name         jsonb   not null,
  description  jsonb   not null,
  category     text    not null check (category in ('coffee', 'desserts', 'breakfast', 'main')),
  price        integer not null check (price > 0),
  image_url    text    not null default '' check (char_length(image_url) <= 2048),
  is_available boolean not null default true,
  -- Display order on the landing page. "by default" lets move_menu_item() swap two positions.
  position     integer generated by default as identity unique,
  created_at   timestamptz not null default now()
);

-- Swaps an item with its neighbour. direction: -1 = up, 1 = down. Runs with the caller's rights (RLS applies).
create or replace function public.move_menu_item(item_id uuid, direction integer)
returns void
language plpgsql
as $$
declare
  current_pos  integer;
  neighbor_id  uuid;
  neighbor_pos integer;
begin
  select position into current_pos from public.menu_items where id = item_id;
  if current_pos is null then
    return;
  end if;

  if direction < 0 then
    select id, position into neighbor_id, neighbor_pos
      from public.menu_items where position < current_pos order by position desc limit 1;
  else
    select id, position into neighbor_id, neighbor_pos
      from public.menu_items where position > current_pos order by position asc limit 1;
  end if;

  if neighbor_id is null then
    return;
  end if;

  -- position is unique, so park the item on a temporary value while swapping
  update public.menu_items set position = -1 where id = item_id;
  update public.menu_items set position = current_pos where id = neighbor_id;
  update public.menu_items set position = neighbor_pos where id = item_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- Bookings (visitors create them, admins manage them)
-- ---------------------------------------------------------------------------
create table if not exists public.bookings (
  id           uuid primary key default gen_random_uuid(),
  name         text    not null check (char_length(name) between 1 and 80),
  phone        text    not null check (char_length(phone) between 5 and 32),
  booking_date date    not null,
  booking_time text    not null check (booking_time ~ '^[0-2][0-9]:[0-5][0-9]$'),
  guests       integer not null check (guests between 1 and 12),
  comment      text    not null default '' check (char_length(comment) <= 500),
  status       text    not null default 'new' check (status in ('new', 'confirmed', 'cancelled')),
  created_at   timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Contact messages (visitors create them, admins read them)
-- ---------------------------------------------------------------------------
create table if not exists public.messages (
  id         uuid primary key default gen_random_uuid(),
  name       text    not null check (char_length(name) between 1 and 80),
  contact    text    not null check (char_length(contact) between 3 and 120),
  message    text    not null check (char_length(message) between 1 and 2000),
  is_read    boolean not null default false,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Row Level Security: nothing is accessible unless a policy allows it
-- ---------------------------------------------------------------------------
alter table public.menu_items enable row level security;
alter table public.bookings   enable row level security;
alter table public.messages   enable row level security;

-- Menu: everyone can read, admins can change
create policy "Menu is public" on public.menu_items
  for select to anon, authenticated using (true);
create policy "Admins insert menu items" on public.menu_items
  for insert to authenticated with check (public.is_admin());
create policy "Admins update menu items" on public.menu_items
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admins delete menu items" on public.menu_items
  for delete to authenticated using (public.is_admin());

-- Bookings: anyone can send a request (always as "new"), only admins can read and manage them
create policy "Anyone can request a booking" on public.bookings
  for insert to anon, authenticated with check (status = 'new');
create policy "Admins read bookings" on public.bookings
  for select to authenticated using (public.is_admin());
create policy "Admins update bookings" on public.bookings
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admins delete bookings" on public.bookings
  for delete to authenticated using (public.is_admin());

-- Messages: same idea (a visitor cannot create a message that is already marked as read)
create policy "Anyone can send a message" on public.messages
  for insert to anon, authenticated with check (is_read = false);
create policy "Admins read messages" on public.messages
  for select to authenticated using (public.is_admin());
create policy "Admins update messages" on public.messages
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admins delete messages" on public.messages
  for delete to authenticated using (public.is_admin());

-- ---------------------------------------------------------------------------
-- Privileges (RLS above decides which rows; grants decide which operations at all)
-- ---------------------------------------------------------------------------
revoke all on public.menu_items, public.bookings, public.messages from anon, authenticated;

grant select on public.menu_items to anon, authenticated;
grant insert, update, delete on public.menu_items to authenticated;

grant insert on public.bookings, public.messages to anon, authenticated;
grant select, update, delete on public.bookings, public.messages to authenticated;

revoke execute on function public.move_menu_item(uuid, integer) from public, anon;
grant execute on function public.move_menu_item(uuid, integer) to authenticated;
